"""The user account model."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import Boolean, DateTime, String, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.clock import utcnow
from app.db.base import Base

if TYPE_CHECKING:  # imported only for type checking, avoids a circular import
    from app.models.conversation import Conversation
    from app.models.file import File
    from app.models.session import UserSession

# 64 characters for the local part + "@" + 255 for the domain is the maximum
# length permitted by the email specification.
EMAIL_MAX_LENGTH = 320


class User(Base):
    """A person with an account.

    Note there is no `password` column and never will be -- only
    `password_hash`. The plaintext password exists in memory for the few
    milliseconds it takes to hash or verify it, and is never persisted or
    logged.
    """

    __tablename__ = "users"

    # A UUID primary key rather than an auto-incrementing integer.
    #
    # Sequential integers leak information: user 1 can see that user 2 exists
    # by changing a URL, and the highest id reveals how many users we have.
    # UUIDs are unguessable and can be generated by the application without a
    # database round trip. `Uuid` is SQLAlchemy's portable type -- a native
    # UUID column on PostgreSQL, a 32-character string on SQLite.
    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)

    # Stored lower-cased and unique. Normalisation happens in the service
    # layer so the behaviour is identical on every database engine, rather
    # than relying on a PostgreSQL-specific case-insensitive column type.
    email: Mapped[str] = mapped_column(
        String(EMAIL_MAX_LENGTH), unique=True, index=True, nullable=False
    )

    password_hash: Mapped[str] = mapped_column(String(255), nullable=False)

    # Lets an account be disabled without deleting it and cascading away all
    # of the user's data.
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False
    )

    sessions: Mapped[list[UserSession]] = relationship(
        back_populates="user",
        # Deleting a user deletes their sessions, so no orphaned session can
        # authenticate as a user who no longer exists.
        cascade="all, delete-orphan",
    )

    conversations: Mapped[list[Conversation]] = relationship(
        back_populates="user",
        # Deleting a user removes their conversations, and the messages inside
        # them cascade in turn. Deleting an account should not leave its chat
        # history readable in the database.
        cascade="all, delete-orphan",
    )

    files: Mapped[list[File]] = relationship(
        back_populates="user",
        # Removes the database rows. KNOWN GAP: the uploaded bytes live on
        # disk, which has no foreign keys, so this cascade orphans them. There
        # is no account-deletion feature yet; when one is built it must unlink
        # each file's storage before deleting the user, because afterwards the
        # rows naming those files are gone and nothing knows what to remove.
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        # Deliberately excludes email and password_hash: repr() output ends up
        # in logs and exception tracebacks, which should not carry personal
        # data or credentials.
        return f"<User id={self.id} active={self.is_active}>"
